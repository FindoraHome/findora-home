create table if not exists public.amazon_order_imports (
  id bigint generated by default as identity primary key,
  fingerprint text not null unique,
  report_date date,
  product_title text not null,
  asin text,
  ordered_count integer not null default 1 check (ordered_count > 0),
  earnings numeric(12,2),
  source_file text,
  imported_at timestamptz not null default now()
);

alter table public.amazon_order_imports enable row level security;

drop policy if exists "Admins manage Amazon order imports" on public.amazon_order_imports;
create policy "Admins manage Amazon order imports"
  on public.amazon_order_imports for all to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

grant select, insert, update, delete on public.amazon_order_imports to authenticated;
grant usage, select on sequence public.amazon_order_imports_id_seq to authenticated;

