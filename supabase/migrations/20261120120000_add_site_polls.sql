create table if not exists public.polls (
  id bigint generated by default as identity primary key,
  question text not null check (char_length(trim(question)) between 3 and 300),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  ends_at timestamptz not null
);

create table if not exists public.poll_options (
  id bigint generated by default as identity primary key,
  poll_id bigint not null references public.polls(id) on delete cascade,
  label text not null check (char_length(trim(label)) between 1 and 200),
  sort_order integer not null default 0
);

create table if not exists public.poll_votes (
  id bigint generated by default as identity primary key,
  poll_id bigint not null references public.polls(id) on delete cascade,
  option_id bigint not null references public.poll_options(id) on delete cascade,
  visitor_token text not null,
  created_at timestamptz not null default now(),
  unique (poll_id, visitor_token)
);

create index if not exists polls_active_ends_at_idx on public.polls(active, ends_at);
create index if not exists poll_options_poll_id_idx on public.poll_options(poll_id, sort_order);
create index if not exists poll_votes_poll_id_idx on public.poll_votes(poll_id);
create index if not exists poll_votes_option_id_idx on public.poll_votes(option_id);

alter table public.polls enable row level security;
alter table public.poll_options enable row level security;
alter table public.poll_votes enable row level security;

create or replace function public.get_active_poll(p_visitor_token text default null)
returns json language plpgsql security definer set search_path = public
as $$
declare
  selected_poll public.polls%rowtype;
  has_voted boolean := false;
  total_votes integer := 0;
  result json;
begin
  select * into selected_poll
  from public.polls
  where active = true and ends_at > now()
  order by created_at desc
  limit 1;

  if selected_poll.id is null then return null; end if;

  if p_visitor_token is not null then
    select exists(select 1 from public.poll_votes where poll_id = selected_poll.id and visitor_token = p_visitor_token)
    into has_voted;
  end if;

  select count(*)::integer into total_votes from public.poll_votes where poll_id = selected_poll.id;

  select json_build_object(
    'id', selected_poll.id,
    'question', selected_poll.question,
    'ends_at', selected_poll.ends_at,
    'has_voted', has_voted,
    'total_votes', total_votes,
    'options', coalesce((
      select json_agg(json_build_object(
        'id', option_row.id,
        'label', option_row.label,
        'votes', case when has_voted then option_row.votes else null end
      ) order by option_row.sort_order, option_row.id)
      from (
        select option_item.id, option_item.label, option_item.sort_order, count(vote.id)::integer as votes
        from public.poll_options option_item
        left join public.poll_votes vote on vote.option_id = option_item.id
        where option_item.poll_id = selected_poll.id
        group by option_item.id, option_item.label, option_item.sort_order
      ) option_row
    ), '[]'::json)
  ) into result;

  return result;
end;
$$;

create or replace function public.vote_in_poll(p_poll_id bigint, p_option_id bigint, p_visitor_token text)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if p_visitor_token is null or char_length(p_visitor_token) < 8 or char_length(p_visitor_token) > 200 then
    raise exception 'Ungültige Besucherkennung.' using errcode = '22023';
  end if;

  if not exists(select 1 from public.polls where id = p_poll_id and active = true and ends_at > now()) then
    raise exception 'Diese Abstimmung ist nicht mehr aktiv.' using errcode = '22023';
  end if;

  if not exists(select 1 from public.poll_options where id = p_option_id and poll_id = p_poll_id) then
    raise exception 'Diese Antwort gehört nicht zur Abstimmung.' using errcode = '22023';
  end if;

  insert into public.poll_votes(poll_id, option_id, visitor_token)
  values (p_poll_id, p_option_id, p_visitor_token);
exception when unique_violation then
  raise exception 'Du hast bereits abgestimmt.' using errcode = '23505';
end;
$$;

create or replace function public.create_site_poll(p_question text, p_options jsonb, p_duration_days integer)
returns bigint language plpgsql security definer set search_path = public
as $$
declare
  new_poll_id bigint;
  option_record record;
begin
  if not public.is_admin() then raise exception 'Nur Admins dürfen Abstimmungen erstellen.' using errcode = '42501'; end if;
  if char_length(trim(coalesce(p_question, ''))) < 3 then raise exception 'Bitte eine Frage eintragen.' using errcode = '22023'; end if;
  if p_duration_days < 1 or p_duration_days > 365 then raise exception 'Die Laufzeit muss zwischen 1 und 365 Tagen liegen.' using errcode = '22023'; end if;
  if jsonb_typeof(p_options) <> 'array' or jsonb_array_length(p_options) < 2 then raise exception 'Mindestens zwei Antworten sind erforderlich.' using errcode = '22023'; end if;

  update public.polls set active = false where active = true;
  insert into public.polls(question, ends_at) values (trim(p_question), now() + make_interval(days => p_duration_days)) returning id into new_poll_id;

  for option_record in select value, ordinality from jsonb_array_elements_text(p_options) with ordinality loop
    if char_length(trim(option_record.value)) > 0 then
      insert into public.poll_options(poll_id, label, sort_order) values (new_poll_id, trim(option_record.value), option_record.ordinality - 1);
    end if;
  end loop;

  if (select count(*) from public.poll_options where poll_id = new_poll_id) < 2 then
    raise exception 'Mindestens zwei ausgefüllte Antworten sind erforderlich.' using errcode = '22023';
  end if;
  return new_poll_id;
end;
$$;

create or replace function public.get_admin_polls()
returns json language plpgsql security definer set search_path = public
as $$
declare result json;
begin
  if not public.is_admin() then raise exception 'Nur Admins dürfen Abstimmungsergebnisse sehen.' using errcode = '42501'; end if;
  select coalesce(json_agg(poll_data order by poll_data.created_at desc), '[]'::json) into result
  from (
    select poll.id, poll.question, poll.active, poll.created_at, poll.ends_at,
      (select count(*)::integer from public.poll_votes vote where vote.poll_id = poll.id) as total_votes,
      coalesce((select json_agg(json_build_object('id', option_item.id, 'label', option_item.label, 'votes', (select count(*)::integer from public.poll_votes vote where vote.option_id = option_item.id)) order by option_item.sort_order, option_item.id) from public.poll_options option_item where option_item.poll_id = poll.id), '[]'::json) as options
    from public.polls poll
    order by poll.created_at desc limit 50
  ) poll_data;
  return result;
end;
$$;

create or replace function public.close_site_poll(p_poll_id bigint)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Nur Admins dürfen Abstimmungen beenden.' using errcode = '42501'; end if;
  update public.polls set active = false where id = p_poll_id;
end;
$$;

create or replace function public.delete_site_poll(p_poll_id bigint)
returns void language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Nur Admins dürfen Abstimmungen löschen.' using errcode = '42501'; end if;
  delete from public.polls where id = p_poll_id;
end;
$$;

